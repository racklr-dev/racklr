#!/usr/bin/env python3
"""formalize.py <dir> — one pass: infer every leaf's effect row, have the LLM
correct the complete set (dropping coarse false positives and decomposing
`dynamic` into concrete effects or the `callback` type variable), and write the
generated declared-function-effects DATA.
"""
import json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
REDUCED_JSON = os.path.join(ROOT, "racklr", "effects",
                            "library-reduced-function-effects.json")
REDUCED_RKT = os.path.join(ROOT, "racklr", "effects",
                           "library-reduced-function-effects.rkt")
FX_ROWS = os.path.join(HERE, "fx-rows.rkt")
JS_FX_ROWS = os.path.join(HERE, "js-ts-fx-rows.rkt")
CLASSIFY = os.path.join(HERE, "classify-functions.sh")


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def detect_host(probe_dir):
    """python or javascript, by the dominant source-file extension."""
    js_exts = {".js", ".mjs", ".ts", ".tsx"}
    py = js = 0
    skip = {"node_modules", ".git", "dist", "build", "vendor", "__pycache__"}
    for root, dirs, files in os.walk(probe_dir):
        dirs[:] = [d for d in dirs if d not in skip]
        for f in files:
            ext = os.path.splitext(f)[1]
            if ext == ".py":
                py += 1
            elif ext in js_exts:
                js += 1
            if py > 5 or js > 5:
                break
    return "javascript" if js > py else "python"


def fx_rows(probe_dir):
    host = detect_host(probe_dir)
    script = JS_FX_ROWS if host == "javascript" else FX_ROWS
    env = dict(os.environ)
    env["PLTCOLLECTS"] = ROOT + ":" + os.path.join(ROOT, "effervesce") + ":"
    res = run(["racket", script, probe_dir], env=env, cwd=ROOT, timeout=600)
    if res.returncode != 0:
        raise SystemExit(f"fx-rows ({host}) failed: {res.stderr[-200:]}")
    return json.loads(res.stdout)


def racket_domains(doms):
    doms = sorted(set(doms))
    if not doms:
        return "'pure"
    if len(doms) == 1:
        return f"'{doms[0]}"
    return "'(" + " ".join(doms) + ")"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    probe_dir = sys.argv[1]
    rows = [r for r in fx_rows(probe_dir) if r["domains"]]
    print(f"effectful leaves: {len(rows)}")
    items = [{"name": r["name"], "domains": r["domains"], "sites": []}
             for r in rows]
    res = run([CLASSIFY], input=json.dumps(items), timeout=1800)
    if res.returncode != 0:
        raise SystemExit(f"classifier failed: {res.stderr[-200:]}")
    corrected = json.loads(res.stdout)
    sidecar = json.load(open(REDUCED_JSON)) if os.path.exists(REDUCED_JSON) else {}
    for it in corrected:
        nm = it["name"]
        # `callback` is the polymorphic type variable: keep it as `dynamic` in
        # the engine vocabulary; concrete effects replace the deferral.
        doms = sorted(set("dynamic" if d == "callback" else d
                          for d in (it.get("domains") or [])))
        if nm and "::" in nm:
            sidecar[nm] = doms
    json.dump(sidecar, open(REDUCED_JSON, "w"), indent=1, sort_keys=True)
    body = "\n".join(
        f"   (cons \"{m}\" '{f}) {v}"
        for n, ds in sorted(sidecar.items())
        for m, _, f in [n.rpartition("::")]
        for v in [racket_domains(ds)]
    )
    open(REDUCED_RKT, "w").write(
        "#lang racket\n\n;; GENERATED by tools/formalize.py\n"
        "(provide reduced-function-effects)\n\n"
        "(define reduced-function-effects\n  (hash\n" + body + "))\n"
    )
    print(f"declared leaves: {len(sidecar)}")


if __name__ == "__main__":
    main()
